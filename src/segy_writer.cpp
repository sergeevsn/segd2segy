SegyWriter::SegyWriter(std::string path) : path_(std::move(path)), output_(path_, std::ios::binary) {
    if (!output_) {
        throw std::runtime_error("Cannot create output file: " + path_);
    }
    stream_buffer_.resize(1 << 20);
    output_.rdbuf()->pubsetbuf(stream_buffer_.data(), static_cast<std::streamsize>(stream_buffer_.size()));
}

void SegyWriter::write_int16_be(std::uint8_t* dst, std::int16_t value) {
    dst[0] = static_cast<std::uint8_t>((value >> 8) & 0xFF);
    dst[1] = static_cast<std::uint8_t>(value & 0xFF);
}

void SegyWriter::write_int32_be(std::uint8_t* dst, std::int32_t value) {
    dst[0] = static_cast<std::uint8_t>((value >> 24) & 0xFF);
    dst[1] = static_cast<std::uint8_t>((value >> 16) & 0xFF);
    dst[2] = static_cast<std::uint8_t>((value >> 8) & 0xFF);
    dst[3] = static_cast<std::uint8_t>(value & 0xFF);
}

void SegyWriter::write_text_header(const std::string& text) {
    std::string padded = text;
    padded.resize(kTextHeaderSize, ' ');
    std::string ebcdic(kTextHeaderSize, ' ');
    for (int i = 0; i < kTextHeaderSize; ++i) {
        ebcdic[static_cast<std::size_t>(i)] = to_ebcdic(padded[static_cast<std::size_t>(i)]);
    }
    write_bytes(output_, ebcdic.data(), ebcdic.size());
}

void SegyWriter::write_binary_header(int sample_interval_us, int samples_per_trace, int format_code) {
    std::uint8_t header[kBinaryHeaderSize]{};
    write_int16_be(header + 16, static_cast<std::int16_t>(sample_interval_us));
    write_int16_be(header + 20, static_cast<std::int16_t>(samples_per_trace));
    write_int16_be(header + 24, static_cast<std::int16_t>(format_code));
    write_bytes(output_, header, sizeof(header));
}

void SegyWriter::write_trace_header(const SegyTraceMeta& meta, std::uint8_t* header) {
    std::memset(header, 0, kTraceHeaderSize);
    write_int32_be(header + 0, meta.tracl);
    write_int32_be(header + 4, meta.tracf);
    write_int32_be(header + 8, meta.fldr);
    write_int32_be(header + 12, meta.tracf);
    write_int32_be(header + 20, meta.cdp);
    write_int16_be(header + 28, 1);  // trid: seismic data
    write_int16_be(header + 114, static_cast<std::int16_t>(meta.ns));
    write_int16_be(header + 116, static_cast<std::int16_t>(meta.dt_us));
    write_int32_be(header + 196, meta.channel_set_number);
    write_int32_be(header + 200, meta.scan_type_number);
}

void SegyWriter::write_trace(const SegyTraceMeta& meta, const std::vector<float>& samples) {
    std::uint8_t header[kTraceHeaderSize]{};
    write_trace_header(meta, header);
    write_bytes(output_, header, sizeof(header));

    if (!samples.empty()) {
        write_bytes(output_, samples.data(), samples.size() * sizeof(float));
    }
    ++trace_count_;
}

